      <h2 id="specializations">Key Electrical Specializations in High Demand</h2>
      <p>Overseas recruitment delegations look for specific skill profiles rather than general handymen:</p>
      <ol>
        <li><strong>Building / MEP Electrician:</strong> Responsible for residential, hotel, and commercial wiring, PVC and GI conduit piping, cable tray installation, DB terminations, and final light fixture wiring.</li>
        <li><strong>Industrial Electrician:</strong> Focused on motor control centers (MCC), direct-on-line (DOL) and star-delta starters, 3-phase transformers, variable frequency drives (VFDs), and industrial machinery wiring.</li>
        <li><strong>Panel Board Wireman:</strong> Specialized in assembling and dressing control panels, busbar fabrication, relay logic circuits, and terminal block labeling.</li>
        <li><strong>Cable Jointer (HV / LV):</strong> Certified technicians who prepare, splice, and terminate high-voltage (11kV to 33kV) armored cables using heat-shrink and cold-shrink jointing kits.</li>
      </ol>

      <h2 id="trade-test-modules">What Examiners Check During the Practical Trade Test</h2>
      <p>At testing venues like Assignment Venue Center in Darbhanga, employer delegations conduct rigorous, hands-on trade evaluations. A typical 2-hour practical test evaluates:</p>
      <ul>
        <li><strong>Distribution Board (DB) Dressing:</strong> Candidates receive an empty consumer unit and must route wires neatly using spiral wraps or cable ties. Phase cables (Brown/Red), Neutral (Blue/Black), and Earth (Green/Yellow) must be connected to their corresponding isolators, RCCBs, and MCBs without exposed copper strands.</li>
        <li><strong>GI / PVC Conduit Bending:</strong> Accurate 90-degree bends and saddle offsets using manual bending springs or mechanical benders. Bends with kinks, flattening, or cracks result in immediate point deductions.</li>
        <li><strong>Motor Starter Wiring:</strong> Candidates are instructed to wire a 3-phase induction motor starter with pushbuttons (Start/Stop), contactor, and thermal overload relay, including indicator lamps.</li>
        <li><strong>Testing &amp; Measurement:</strong> Practical demonstration of a digital Multimeter and Megohmmeter (Megger) to perform insulation resistance testing (minimum 1 Megohm standard) and continuity tests.</li>
      </ul>

