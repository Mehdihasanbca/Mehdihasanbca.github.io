      <h2 id="allowances">Standard Allowances &amp; Mandatory Company Provisions</h2>
      <p>Under UAE labor regulations, legitimate employers must provide basic welfare benefits on top of your contractual salary:</p>
      <ul>
        <li><strong>Accommodation:</strong> Reputable employers provide free, air-conditioned accommodation in licensed labor communities (such as Sonapur, Al Quoz, or Jebel Ali) compliant with MOHRE health and safety guidelines. If living out, a housing allowance of AED 400 to AED 800 must be specified.</li>
        <li><strong>Transportation:</strong> Free bus transport between the labor camp and work sites is standard.</li>
        <li><strong>Food / Messing:</strong> Many companies run subsidized or free camp mess facilities serving Indian cuisine. If cooking your own food, a food allowance (typically AED 250 to AED 350) is credited with your salary.</li>
        <li><strong>Medical Insurance:</strong> Health insurance cards are legally mandatory in Dubai (regulated by DHA). Employers must provide full coverage with zero cost deduction from the worker.</li>
        <li><strong>Annual Ticket:</strong> Free economy airfare to India and return every two years (or annually depending on contract category).</li>
      </ul>

      <h2 id="overtime-wps">Overtime Calculation and the Wage Protection System (WPS)</h2>
      <p>Standard working hours in the UAE are 8 hours per day, 48 hours per week (or 6 hours per day during the holy month of Ramadan). Any extra hours worked are classified as overtime:</p>
      <p><strong>Overtime Rate:</strong> Normal overtime during daylight hours must be paid at basic hourly pay plus at least 25%. Overtime performed between 9 PM and 4 AM, or on scheduled rest days/public holidays, must be compensated at basic pay plus at least 50%.</p>
      <p><strong>Wage Protection System (WPS):</strong> In the UAE, cash payments for labor are illegal. Every worker receives an electronic bank card or C3 exchange card through WPS. If an employer fails to pay the exact contract salary into the bank account on time, the MOHRE system automatically freezes the company&rsquo;s hiring licenses and initiates governmental audits.</p>

      <h2 id="scam-detection">Red Flags: Spotting Fake Dubai Salary Offers</h2>
      <p>Subagents and fraudsters targeting candidates in Bihar often fabricate offer letters promising unrealistic salaries. Keep these safeguards in mind:</p>
      <ol>
        <li><strong>Unrealistic Wage Rates:</strong> If an agency in Patna or Delhi offers you AED 5,000 for a basic building electrician role without advanced engineering qualifications, it is almost certainly a scam designed to extract money upfront.</li>
        <li><strong>Visit Visa Traps:</strong> Legitimate firms issue official <em>Entry Permits for Employment</em> approved by GDRFA. Working on a tourist or visit visa is strictly illegal in the UAE and can lead to immediate arrest, detention, deportation, and an irreversible travel ban.</li>
        <li><strong>Demand for Processing Fees:</strong> Under the Indian Emigration Act 1983 and UAE law, workers should never pay recruitment charges. Legitimate employers bear all visa, processing, and mobilization fees.</li>
      </ol>

