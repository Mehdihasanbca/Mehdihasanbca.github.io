      <h2 id="what-is-gamca">What is the GAMCA / Wafid Medical Examination?</h2>
      <p>Before any Indian citizen can receive an employment visa or residence permit for Saudi Arabia, the United Arab Emirates, Qatar, Kuwait, Bahrain, or Oman, they must obtain a digital medical fitness certificate from an accredited clinic. This protocol is overseen by the <strong>Gulf Health Council (GHC)</strong>, historically known as GAMCA (Gulf Approved Medical Centers Association) and now officially accessed via the <strong>Wafid portal (<a href="https://wafid.com" target="_blank" rel="noopener noreferrer">wafid.com</a>)</strong>.</p>
      <p>The objective of the examination is to prevent the introduction of infectious diseases into the host nation and verify that candidates possess the physical fitness necessary to undertake demanding industrial, construction, and mechanical duties in extreme climatic conditions.</p>

      <h2 id="booking-slip">How to Book a Wafid Medical Slip Online</h2>
      <p>Appointment booking is entirely automated through the centralized Wafid online portal. Candidates should follow these steps:</p>
      <ol>
        <li>Visit the official portal at <a href="https://wafid.com" target="_blank" rel="noopener noreferrer">wafid.com</a> and click on <em>&ldquo;Book an Appointment&rdquo;</em>.</li>
        <li>Enter your nationality (India), country of destination (e.g., Saudi Arabia or UAE), and select your nearest test city (e.g., Patna, Kolkata, Lucknow, or Delhi).</li>
        <li>Provide your full passport details: Passport Number, Date of Birth, Expiry Date, and your specific trade as stated in your job agreement.</li>
        <li>Pay the standard international slip generation fee ($10 USD, equivalent to approximately ₹850 to ₹950 INR) via debit or credit card.</li>
        <li><strong>Automated Center Allocation:</strong> The Wafid computer algorithm automatically assigns you to a registered clinic in your chosen city. <em>No agent or clinic can manually select their own facility</em>—this randomization prevents bribery and fraudulent test alterations.</li>
      </ol>

      <h2 id="required-tests">Mandatory Clinical Tests Performed</h2>
      <p>When you arrive at the designated clinic with your original passport and appointment slip, you will undergo a comprehensive two-stage evaluation:</p>
      <ul>
        <li><strong>Physical Examination:</strong> Vision check (Snellen chart), color blindness test (Ishihara plates), hearing acuity, blood pressure, pulse, and physical check for visible hernias, hydrocele, or limb deformities.</li>
        <li><strong>Chest X-Ray:</strong> Digital chest radiograph to detect active pulmonary tuberculosis (TB), healed fibro-calcified lesions, pleural thickening, or cardiac enlargement.</li>
        <li><strong>Serology &amp; Blood Testing:</strong> Tests for HIV 1 &amp; 2, Hepatitis B Surface Antigen (HBsAg), Hepatitis C Virus antibodies (Anti-HCV), VDRL/TPHA for Syphilis, and Malaria parasites.</li>
        <li><strong>Biochemistry &amp; Urine Analysis:</strong> Fasting blood sugar, liver function tests (SGPT/SGOT, Bilirubin), kidney parameters (Serum Creatinine), and urinalysis for Albumin, Sugar, and microscopic Hematuria.</li>
      </ul>

      <h2 id="unfitness-causes">Common Causes of Medical Unfitness (&ldquo;Fit vs. Unfit&rdquo;)</h2>
      <p>The Gulf Health Council maintains a strict zero-tolerance policy on several medical parameters. Being declared &ldquo;Unfit&rdquo; can lead to a 6-month to permanent ban from entering the GCC:</p>
      <ol>
        <li><strong>Lung Scars:</strong> Any historic evidence of treated tuberculosis or chest trauma that left a permanent scar or calcification on the lung can result in immediate unfitness under strict GCC radiology guidelines.</li>
        <li><strong>Active Hepatitis B or C:</strong> A positive blood result for HBsAg or HCV antibodies results in an automatic, permanent unfitness designation across all Gulf countries.</li>
        <li><strong>Uncontrolled Hypertension or Diabetes:</strong> Severely elevated blood pressure or high fasting blood sugar can cause temporary suspension (&ldquo;Repeat / Hold&rdquo;). Candidates should ensure their vitals are managed medically prior to test day.</li>
        <li><strong>Hernia or Hydrocele:</strong> Unrepaired surgical hernias will cause temporary failure until treated and completely healed with an authorized surgeon&rsquo;s discharge summary.</li>
      </ol>

      <h2 id="bihar-centers">Approved Testing Centers for Bihar Candidates</h2>
      <p>For candidates residing in Darbhanga, Madhubani, Samastipur, Muzaffarpur, or Begusarai, the primary testing city allocated on the Wafid portal is <strong>Patna</strong>. In Patna, several accredited clinics operate under the GHC umbrella around Ashiana Road, Exhibition Road, and Bailey Road.</p>
      <p>Always ensure that you attend only the exact medical center named on your printed Wafid slip. Attending any other clinic—even if they claim to have GAMCA accreditation—will result in wasted money, because the computerized results will not sync to the central GCC immigration servers.</p>

