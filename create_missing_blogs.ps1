      <h2 id="what-is-6g">What is the 6G Welding Position?</h2>
      <p>In high-pressure piping, refinery construction, and offshore drilling platforms, pipe joints cannot be rotated during fabrication. The pipe must be welded in whatever angle or orientation the engineering layout dictates.</p>
      <p>The <strong>6G position</strong> under ASME Section IX (or AWS D1.1 / EN ISO 9606-1) places a test pipe coupon inclined at a fixed <strong>45-degree angle</strong> (&plusmn;5&deg;) without rotation. Because the welder must execute welds across flat, vertical, overhead, and horizontal positions in a single continuous joint, qualifying in 6G certifies a tradesman for virtually all welding positions (1G, 2G, 3G, 4G, 5G, and 6G).</p>

      <h2 id="fitup-bevel">Step 1: Fit-Up and Bevel Preparation</h2>
      <p>A flawless weld begins with mechanical joint preparation. Examiners at testing venues like Assignment Venue Center inspect the test piece before the arc is ever struck:</p>
      <ul>
        <li><strong>Bevel Angle:</strong> Standard 37.5-degree bevel (total 75-degree included V-groove angle).</li>
        <li><strong>Root Face (&ldquo;Land&rdquo;):</strong> 1.5mm to 2.5mm uniform root face ground smoothly along the circumference without knife edges.</li>
        <li><strong>Root Gap:</strong> 2.5mm to 3.2mm uniform root gap maintained with a spacer rod or TIG filler wire.</li>
        <li><strong>Tack Welds:</strong> Typically 4 small bridge tacks (or feather-edge tacks) at 12, 3, 6, and 9 o&rsquo;clock positions using GTAW with complete fusion.</li>
        <li><strong>Cleaning:</strong> Bright metal grinding to at least 25mm back from the bevel inside and out to remove mill scale, rust, and moisture.</li>
      </ul>

      <h2 id="root-pass">Step 2: TIG (GTAW) Root Pass Mastery</h2>
      <p>For cross-country oil pipelines and refinery process lines, the root run is virtually always performed using <strong>Gas Tungsten Arc Welding (GTAW / TIG)</strong> with 99.99% pure Argon shielding gas (and an Argon backing purge for stainless or chrome alloys):</p>
      <p><strong>Parameters:</strong> 2.4mm 2% Thoriated or Lanthanated Tungsten electrode, ER70S-6 filler wire (2.0mm or 2.4mm), amperage set between 85A and 110A DCEN (Direct Current Electrode Negative).</p>
      <p><strong>Key Examiner Checks:</strong> Full root penetration with a smooth, concave-to-flush internal bead reinforcement (0.5mm to 1.5mm). Lack of penetration (LOP), root concavity (&ldquo;suck-back&rdquo;), or burn-through causes immediate coupon rejection.</p>

      <h2 id="hot-capping">Step 3: Hot Pass, Fill &amp; Cap using SMAW (E7018)</h2>
      <p>Once the root pass is approved by the welding inspector, the remaining passes are deposited using <strong>Shielded Metal Arc Welding (SMAW / Stick)</strong> or continued GTAW:</p>
      <ol>
        <li><strong>Hot Pass:</strong> Deposited quickly after root cleaning using E7018 low-hydrogen electrodes (or E6010 for downhill cellulosic pipelines) to burn out minor inclusions and build bead thickness.</li>
        <li><strong>Fill Passes:</strong> Multi-pass stringer beads or slight weaves deposited with complete inter-pass slag removal using chipping hammer and wire wheel. Interpass temperatures must be monitored (typically below 250&deg;C).</li>
        <li><strong>Capping Pass:</strong> The visible cosmetic crown. Width must not extend more than 2.5mm beyond the bevel edge on either side; cap height should be uniform between 1.0mm and 2.5mm with smooth wash-in to the pipe wall without undercut.</li>
      </ol>

      <h2 id="inspection-criteria">Visual and Radiographic Testing (RT / X-Ray)</h2>
      <p>After cooling, the coupon undergoes strict non-destructive examination (NDE):</p>
      <ul>
        <li><strong>Visual Inspection (VT):</strong> Zero cracks, zero lack of fusion, undercut depth strictly &le; 0.5mm, zero excessive spatter, and complete arc strike removal.</li>
        <li><strong>Radiographic Testing (RT / X-Ray):</strong> An industrial gamma source (Iridium-192 or X-Ray tube) produces radiographic films of the entire joint. The film is evaluated against ASME B31.3 Severe Cyclic or API 1104 standards: no tungsten inclusions, no porosity clusters, and zero linear indications.</li>
        <li><strong>Bend Tests:</strong> In mechanical testing, 4 side-bend (or root/face bend) specimens are bent around a plunger through 180 degrees. No tear exceeding 3mm is permitted.</li>
      </ul>

